export function localizeCategoryName(slug: string, name: string, lang: Lang): string {
  // Provider / studio brand names stay in English.
  if (BRAND_NAME_SLUGS.has(slug)) return name
  if (lang === 'bn' && CATEGORY_NAME_BN[slug]) return CATEGORY_NAME_BN[slug]
  return name
}

export function localizeCategoryDesc(slug: string, description: string, lang: Lang): string {
  if (lang === 'bn' && CATEGORY_DESC_BN[slug]) return CATEGORY_DESC_BN[slug]
  return description
}

export function fillMessage(template: string, vars?: Record<string, string | number>): string {
  if (!vars) return template
  return template.replace(/\{(\w+)\}/g, (_, key: string) =>
    vars[key] !== undefined && vars[key] !== null ? String(vars[key]) : `{${key}}`,
  )
}
